#!/usr/bin/env python3
"""Group, check and document the DVC-tracked data (see data/catalog.yaml, DATA.md).

  catalog.py targets [--all] [GROUP...]   dvc pull targets of the groups (no group = the default ones)
  catalog.py check                        every *.dvc matches exactly one group; no group is empty
  catalog.py docs                         rewrite the generated table in DATA.md
"""
import argparse
import glob
import os
import sys

import yaml

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
CATALOG = os.path.join(ROOT, "data", "catalog.yaml")
DOC = os.path.join(ROOT, "DATA.md")
START, END = "<!-- catalog:start (generated by tools/data/catalog.py docs) -->", "<!-- catalog:end -->"
SKIP_DIRS = {".git", ".dvc", "node_modules", "helper-repos", ".data-remote", "frontend", "scratch"}


def load():
    with open(CATALOG) as f:
        return yaml.safe_load(f)["groups"]


def all_pointers():
    found = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        found += [os.path.relpath(os.path.join(dirpath, n), ROOT) for n in filenames if n.endswith(".dvc")]
    return sorted(found)


def assign(groups):
    """pointer -> first group whose globs match it."""
    owner = {}
    for name, g in groups.items():
        for pattern in g.get("paths", []):
            for hit in glob.glob(os.path.join(ROOT, pattern), recursive=True):
                owner.setdefault(os.path.relpath(hit, ROOT), name)
    return owner


def describe(pointer):
    with open(os.path.join(ROOT, pointer)) as f:
        out = yaml.safe_load(f)["outs"][0]
    return out["size"], out.get("nfiles", 1)


def human(n):
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024


def cmd_targets(args):
    groups = load()
    names = list(groups) if args.all else args.groups or [n for n, g in groups.items() if g.get("default")]
    unknown = [n for n in names if n not in groups]
    if unknown:
        sys.exit(f"unknown group(s): {', '.join(unknown)}; known: {', '.join(groups)}")
    owner = assign(groups)
    for n in names:
        print("\n".join(p for p, o in sorted(owner.items()) if o == n))
        print("\n".join(groups[n].get("stages", [])), end="\n" if groups[n].get("stages") else "")


def cmd_check(_):
    groups = load()
    owner = assign(groups)
    orphans = [p for p in all_pointers() if p not in owner]
    empty = [n for n in groups if n not in owner.values() and not groups[n].get("stages")]
    if orphans:
        print("pointers in no group (add a glob to data/catalog.yaml):", *orphans, sep="\n  ", file=sys.stderr)
    if empty:
        print("groups matching nothing:", *empty, sep="\n  ", file=sys.stderr)
    sys.exit(1 if orphans or empty else 0)


def cmd_docs(_):
    groups = load()
    owner = assign(groups)
    rows = ["| Group | Use case | Artifacts | Size | Pulled by default | What it is |", "|---|---|---:|---:|:-:|---|"]
    detail = []
    for name, g in groups.items():
        members = sorted(p for p, o in owner.items() if o == name)
        size = sum(describe(p)[0] for p in members)
        files = sum(describe(p)[1] for p in members)
        rows.append(f"| `{name}` | {g['use_case']} | {len(members)} ({files} files) | {human(size)} | "
                    f"{'yes' if g.get('default') else 'no'} | {g['description']} |")
        detail += [f"### `{name}`", ""] + [f"- `{p[:-4]}` ({human(describe(p)[0])})" for p in members]
        detail += [f"- stage `{s}` (dvc.yaml)" for s in g.get("stages", [])] + [""]
    generated = "\n".join([START, "", *rows, "", "#### Every artifact", "", *detail, END])
    with open(DOC) as f:
        text = f.read()
    if START not in text or END not in text:
        sys.exit(f"{DOC} has no catalog markers")
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    with open(DOC, "w") as f:
        f.write(head + generated + tail)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    t = sub.add_parser("targets")
    t.add_argument("--all", action="store_true")
    t.add_argument("groups", nargs="*")
    t.set_defaults(fn=cmd_targets)
    sub.add_parser("check").set_defaults(fn=cmd_check)
    sub.add_parser("docs").set_defaults(fn=cmd_docs)
    args = ap.parse_args()
    args.fn(args)


if __name__ == "__main__":
    main()
