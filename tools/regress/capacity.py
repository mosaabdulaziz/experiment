"""Capacity: how far can the pipeline be pushed on this machine?

The golden replays feed a clip at its own frame rate with a real-time-paced sink, so their fps says "kept up with the source", not what the
machine can do. This module measures the limits:

* ceiling: the same replay with the pacing switched off (`sink_sync: false`, `mux_sync_inputs: 0`): the pipeline's top throughput;
* cameras: the same clip as N sources, paced (real time) and not paced: how many cameras of that use case the machine keeps up with
  (every camera at its source rate, no drops, no stalls), and the aggregate ceiling;
* models: the attendance detector swapped for each size the repo has, ceiling and cameras, with the engine files protected (a swap
  rewrites the single root engine slot the baselines depend on);
* engines: `trtexec` on each ONNX: GPU time per frame, independent of the pipeline.

Each run is an ordinary golden replay of a generated overlay config (`tests/configs/golden-cap-*.yaml`, written next to the real ones and
removed afterwards), so everything the harness records (stage timers, GPU counters, drops) comes with it. Extra cameras replay the same
clip with the same roles; a role that needs per-camera setup (zones) runs without it on the copies, so its cameras figure is a little optimistic.

Pure helpers first (tested on synthetic text and results), then the runner.
"""
import json
import os
import re
import shutil
import subprocess
import sys

SOURCE_LINE = re.compile(r"^(\s*-\s*\{)\s*id:\s*([^,\s}]+)(.*\}\s*)$")
REALTIME_FRACTION = 0.95            # a camera counts as kept up with when its median fps is at least this share of the source rate
DEFAULT_CONFIGS = ["attendance", "zones", "fire", "barber", "ppe", "fall_detection", "shelf", "proximity"]


# ---------------------------------------------------------------- planning
def read_sources(base_text: str) -> list:
    """The `sources:` entries of a golden config: [(id, rest-of-line)], in order."""
    out, inside = [], False
    for line in base_text.splitlines():
        if re.match(r"^sources:\s*$", line):
            inside = True
            continue
        if inside:
            m = SOURCE_LINE.match(line)
            if m:
                out.append((m.group(2), line))
            elif line.strip() and not line.startswith((" ", "\t", "#")):
                break
    return out


def replicate_sources(base_text: str, n: int) -> list:
    """`n` source lines: the base's first source with ids cam-1..cam-n (its id kept for the first one)."""
    src = read_sources(base_text)
    if not src:
        raise ValueError("the base config has no sources: block of one-line entries")
    first_id, line = src[0]
    lines = []
    for i in range(1, n + 1):
        new_id = first_id if i == 1 else f"{first_id}-{i}"
        lines.append(re.sub(r"(\{\s*id:\s*)[^,\s}]+", lambda m: m.group(1) + new_id, line, count=1))
    return lines


def run_name(base: str, n: int, paced: bool, tag: str = "") -> str:
    return f"cap-{base}{('-' + tag) if tag else ''}-n{n}-{'rt' if paced else 'max'}"


def overlay_text(base: str, base_text: str, n: int, paced: bool, extra: dict = None) -> str:
    """The overlay config: the real golden config, N copies of its source, pacing on or off, extra top-level keys."""
    lines = [f"# generated by `regress capacity`; not a product, not committed", f"extends: golden-{base}.yaml", "file_loop: false"]
    if not paced:
        lines += ["sink_sync: false", "mux_sync_inputs: 0"]
    for k, v in (extra or {}).items():
        lines.append(f"{k}: {json.dumps(v)}")
    if n > 1:
        lines.append("sources:")
        lines += replicate_sources(base_text, n)
    return "\n".join(lines) + "\n"


def plan_limits(configs: list, cameras: list) -> list:
    """[(config, n, paced)] to run: the ceiling at 1 camera, real time at each camera count, and the ceiling at the largest count."""
    cams = sorted(set(cameras) | {1})
    runs = []
    for c in configs:
        runs.append((c, 1, False))
        for n in cams:
            runs.append((c, n, True))
        if cams[-1] > 1:
            runs.append((c, cams[-1], False))
    return runs


# ---------------------------------------------------------------- summarising
def entry_of(result: dict, name: str) -> dict:
    """One replay's numbers from a regress results file."""
    g = result.get("correctness", {}).get("golden", {}).get(name, {})
    r = (result.get("runtime") or {}).get(name, {}) or {}
    if not g.get("ran"):
        return {"ran": False, "error": str(g.get("error"))[-160:]}
    fps = {c: v for c, v in (r.get("fps") or {}).items()}
    med = [v.get("median") for v in fps.values() if v.get("median") is not None]
    p10 = [v.get("p10") for v in fps.values() if v.get("p10") is not None]
    drops = r.get("drops") or {}
    nv = ((r.get("gpu_counters") or {}).get("nvml")) or {}
    stages = {k: v.get("avg_ms") for k, v in (r.get("gpu_stages") or {}).items()}
    return {"ran": True, "noisy": bool(result.get("noisy")), "noise_reasons": (result.get("guardrails") or {}).get("reasons") or [], "cameras": len(fps), "per_cam_median": [round(x, 2) for x in med], "min_cam_median": round(min(med), 2) if med else None,
            "min_cam_p10": round(min(p10), 2) if p10 else None, "aggregate_fps": round(sum(med), 2) if med else None,
            "drops": sum(float(v or 0) for k, v in drops.items() if k != "stall_episodes"), "stalls": float(drops.get("stall_episodes") or 0),
            "gpu_util": (nv.get("gpu_util") or {}).get("median"), "power_w": (nv.get("power_w") or {}).get("median"),
            "throttled_fraction": nv.get("throttled_fraction"), "gpu_added_mib": (r.get("gpu_memory") or {}).get("added_mib"),
            "boot_s": r.get("boot_to_first_fps_s"), "stage_ms": stages, "entries": g.get("entries")}


def realtime_ok(entry: dict, source_fps: float) -> bool:
    """Every camera kept up with the source: median fps at least 95 % of it, nothing dropped, no stall."""
    return bool(entry.get("ran") and entry.get("min_cam_median") is not None and source_fps
                and entry["min_cam_median"] >= REALTIME_FRACTION * source_fps and not entry.get("drops") and not entry.get("stalls"))


def summarize(entries: dict, source_fps: dict = None) -> dict:
    """{config: {...}} from {(config, n, paced): entry}: source rate, ceilings, the largest camera count kept up with.
    `source_fps`: {config: the clip's own frame rate}; without it the 1-camera real-time run's rate stands in (wrong for a config that
    cannot keep up with one camera)."""
    by_cfg = {}
    for (cfg, n, paced), e in entries.items():
        by_cfg.setdefault(cfg, {})[(n, paced)] = e
    out = {}
    for cfg, runs in sorted(by_cfg.items()):
        rt1 = runs.get((1, True), {})
        src = (source_fps or {}).get(cfg) or ((rt1.get("per_cam_median") or [None])[0] if rt1.get("ran") else None)
        ceil1 = runs.get((1, False), {})
        cams = sorted(n for (n, paced) in runs if paced)
        ok_cams, stop = 0, False
        for n in cams:
            if not stop and realtime_ok(runs[(n, True)], src):
                ok_cams = n
            else:
                stop = True
        maxn = max((n for (n, paced) in runs if not paced), default=1)
        agg_max = (runs.get((maxn, False)) or {}).get("aggregate_fps")
        noisy = sorted(f"n{n}-{'rt' if paced else 'max'}" for (n, paced), e in runs.items() if e.get("noisy"))
        out[cfg] = {"noisy_steps": noisy, "source_fps": src, "ceiling_fps_1cam": ceil1.get("aggregate_fps") if ceil1.get("ran") else None,
                    "headroom_1cam": round(ceil1["aggregate_fps"] / src, 2) if ceil1.get("ran") and src and ceil1.get("aggregate_fps") else None,
                    "realtime_cameras_tested_ok": ok_cams, "cameras_tested": cams,
                    "aggregate_ceiling_fps": agg_max, "aggregate_ceiling_cameras": maxn,
                    "cameras_by_ceiling": round(agg_max / src, 1) if agg_max and src else None,
                    "runs": {f"n{n}-{'rt' if paced else 'max'}": e for (n, paced), e in sorted(runs.items())}}
    return out


def render(summary: dict) -> str:
    lines = [f"{'config':<16}{'source fps':>11}{'1-cam ceiling':>14}{'headroom':>9}{'real-time cams (tested ok)':>28}{'aggregate ceiling':>19}{'~cams by ceiling':>17}"]
    for cfg, s in summary.items():
        lines.append(f"{cfg + (' *' if s.get('noisy_steps') else ''):<16}{str(s['source_fps']):>11}{str(s['ceiling_fps_1cam']):>14}{(str(s['headroom_1cam']) + 'x') if s['headroom_1cam'] else '-':>9}"
                     f"{str(s['realtime_cameras_tested_ok']) + ' of ' + str(s['cameras_tested']):>28}"
                     f"{(str(s['aggregate_ceiling_fps']) + ' fps @' + str(s['aggregate_ceiling_cameras'])) if s['aggregate_ceiling_fps'] else '-':>19}"
                     f"{str(s['cameras_by_ceiling']) if s['cameras_by_ceiling'] else '-':>17}")
    if any(v.get("noisy_steps") for v in summary.values()):
        lines.append("* some steps ran while something else was using the GPU (marked noisy in their entries): read those numbers as lower bounds")
    return "\n".join(lines)


# ---------------------------------------------------------------- model variants (the attendance detector)
MODELS = {   # name -> (pgie_config relative to the repo, precision note)
    "yolo11x": ("perception/models/DeepStream-Yolo/config_infer_primary_yolo11_x.txt", "fp32 (the product's default)"),
    "yolo11l": ("perception/models/DeepStream-Yolo/config_infer_primary_yolo11_l.txt", "fp32"),
    "yolo11m": ("perception/models/DeepStream-Yolo/config_infer_primary_yolo11_m.txt", "fp16"),
    "yolo11s": ("perception/models/DeepStream-Yolo/config_infer_primary_yolo11.txt", "fp16"),
    "damoyolo_s": ("perception/models/DeepStream-Yolo/config_infer_primary_damoyolo.txt", "fp16"),
}
FP16_OF = {"yolo11x": "yolo11x-fp16", "yolo11l": "yolo11l-fp16"}      # same model at fp16, to compare sizes at one precision


def fp16_config_text(text: str) -> str:
    """A copy of a pgie config with network-mode=2 (FP16)."""
    if re.search(r"^network-mode=", text, re.M):
        return re.sub(r"^network-mode=.*$", "network-mode=2", text, flags=re.M)
    return text.rstrip() + "\nnetwork-mode=2\n"


# ---------------------------------------------------------------- engine protection
def engine_files(repo: str) -> list:
    out = []
    for root in (repo, os.path.join(repo, "perception", "models"), os.path.join(repo, "products")):
        for dp, _dn, fn in os.walk(root):
            if root == repo and dp != repo:
                continue
            if "node_modules" in dp or ".venv" in dp:
                continue
            for f in fn:
                if f.endswith(".engine") or (root == repo and re.fullmatch(r"model_b\d+_gpu\d+_fp\d+\.engine\.src", f)):
                    out.append(os.path.relpath(os.path.join(dp, f), repo))
    return sorted(set(out))


def backup_engines(repo: str, dest: str) -> list:
    files = engine_files(repo)
    for rel in files:
        os.makedirs(os.path.dirname(os.path.join(dest, rel)), exist_ok=True)
        shutil.copy2(os.path.join(repo, rel), os.path.join(dest, rel))
    return files


def restore_engines(repo: str, dest: str, files: list) -> dict:
    """Put the backed-up engine files back, byte for byte, and remove the engine files that were not there at backup time.
    A replay's container runs as root and rewrites engines as root-owned files this user cannot open for writing (found 2026-11-18: the first
    restore died on one), so a file that cannot be overwritten is replaced instead: the directory is ours. Every restored file is compared with
    its backup and a difference raises: a silent failure here would leave a changed baseline behind. -> {"restored": n, "removed": [...]}."""
    import filecmp
    keep = set(files)
    for rel in files:
        src, dst = os.path.join(dest, rel), os.path.join(repo, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        try:
            shutil.copy2(src, dst)
        except PermissionError:
            os.unlink(dst)
            shutil.copy2(src, dst)
        if not filecmp.cmp(src, dst, shallow=False):
            raise RuntimeError(f"engine {rel} differs from its backup after the restore")
    removed = []
    for rel in engine_files(repo):
        if rel not in keep:
            os.unlink(os.path.join(repo, rel))
            removed.append(rel)
    return {"restored": len(files), "removed": removed}


# ---------------------------------------------------------------- trtexec (the model alone)
def parse_trtexec(text: str) -> dict:
    """GPU compute time (ms, median) and throughput (qps) from a trtexec log."""
    out = {}
    m = re.search(r"GPU Compute Time:.*?median = ([\d.]+) ms", text)
    if m:
        out["gpu_ms_median"] = float(m.group(1))
    m = re.search(r"Throughput: ([\d.]+) qps", text)
    if m:
        out["throughput_qps"] = float(m.group(1))
    m = re.search(r"Latency:.*?median = ([\d.]+) ms", text)
    if m:
        out["latency_ms_median"] = float(m.group(1))
    return out


# ---------------------------------------------------------------- the runner
def _read(path: str) -> str:
    with open(path) as f:
        return f.read()


def write_overlays(repo: str, runs: list, extra_for=None) -> dict:
    """Write one overlay per (config, n, paced[, tag]) and return {run tuple: run name}."""
    names = {}
    for run in runs:
        cfg, n, paced = run[:3]
        tag = run[3] if len(run) > 3 else ""
        base_text = _read(os.path.join(repo, "tests", "configs", f"golden-{cfg}.yaml"))
        name = run_name(cfg, n, paced, tag)
        extra = (extra_for(run) if extra_for else None)
        with open(os.path.join(repo, "tests", "configs", f"golden-{name}.yaml"), "w") as f:
            f.write(overlay_text(cfg, base_text, n, paced, extra))
        names[run] = name
    return names


def remove_overlays(repo: str, names: dict) -> None:
    for name in names.values():
        try:
            os.remove(os.path.join(repo, "tests", "configs", f"golden-{name}.yaml"))
        except OSError:
            pass


def wait_idle(repo: str, minutes: float = 8.0) -> bool:
    """Poll the harness's idle check (GPU under its limit) until it passes or the time is up. True = idle."""
    import time
    env = {**os.environ, "PYTHONPATH": os.path.join(repo, "tools")}
    deadline = time.time() + minutes * 60
    while True:
        r = subprocess.run([sys.executable, "-m", "regress", "idle"], cwd=repo, env=env, capture_output=True)
        if r.returncode == 0:
            return True
        if time.time() >= deadline:
            return False
        time.sleep(20)


RESUME = False          # reuse a step's results file when it already exists (set by --resume)


def run_replays(repo: str, names: list, out_json: str, timeout_s: int = 3 * 3600) -> dict:
    """The harness's own `run --only golden` of the generated configs, from the checkout that has the data. Waits for an idle GPU first
    (the replay then runs anyway if it never comes, marked noisy by the harness)."""
    if RESUME and os.path.exists(out_json):
        try:
            return json.load(open(out_json))
        except ValueError:
            pass
    wait_idle(repo)
    env = {**os.environ, "PYTHONPATH": os.path.join(repo, "tools"), "GOLDEN_MAX": os.environ.get("GOLDEN_MAX", "900")}
    cmd = [sys.executable, "-m", "regress", "run", "--only", "golden", "--configs", ",".join(names), "--no-dcgm", "--allow-noisy", "--out", out_json]
    subprocess.run(cmd, cwd=repo, env=env, timeout=timeout_s, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if not os.path.exists(out_json):
        return {}
    return json.load(open(out_json))


# ---------------------------------------------------------------- the three measurements
def source_rate(repo: str, base: str) -> float:
    """The clip's own frame rate (ffprobe), for the first source of a golden config; 0 when it cannot be read."""
    text = _read(os.path.join(repo, "tests", "configs", f"golden-{base}.yaml"))
    m = re.search(r'uri:\s*"file:///workspace/iris/([^"]+)"', text)
    if not m:
        return 0.0
    r = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=r_frame_rate", "-of", "csv=p=0",
                        os.path.join(repo, m.group(1))], capture_output=True, text=True)
    try:
        num, _, den = r.stdout.strip().partition("/")
        return round(float(num) / float(den or 1), 2)
    except ValueError:
        return 0.0


def measure_one(repo: str, label: str, base: str, cameras: list, out_dir: str, extra: dict = None, src: float = 0.0, tag: str = None,
                ceilings: bool = True) -> dict:
    """The camera ladder of one use case: ceiling at 1, real time at 1 and then each larger count until one is not kept up with, then the
    ceiling at the last count tried. One harness replay per step. {(label, n, paced): entry}."""
    entries = {}
    tag = ("" if label == base else label) if tag is None else tag

    def step(n, paced):
        name = run_name(base, n, paced, tag)
        names = write_overlays(repo, [(base, n, paced, tag)], extra_for=(lambda run: extra) if extra else None)
        try:
            res = run_replays(repo, [name], os.path.join(out_dir, f"{name}.json"))
        finally:
            remove_overlays(repo, names)
        e = entry_of(res, name)
        entries[(label, n, paced)] = e
        return e

    if ceilings:
        step(1, False)
    e1 = step(1, True)
    src = src or ((e1.get("per_cam_median") or [0])[0] if e1.get("ran") else 0)
    last = 1
    if realtime_ok(e1, src):
        for n in sorted(set(cameras) - {1}):
            last = n
            if not realtime_ok(step(n, True), src):
                break
    if last > 1 and ceilings:
        step(last, False)
    return entries


def measure_limits(repo: str, configs: list, cameras: list, out_dir: str, analysis_fps: int = 0) -> dict:
    """Ceiling and real-time cameras for each golden config. With `analysis_fps` the pipeline analyses that many frames a second per camera
    (the config's `analysis_fps`), labelled `<config>@af<N>`; the source rate it must keep up with is then what the 1-camera real-time run achieves
    (videorate quantises the rate, so the nominal number is not what comes out)."""
    os.makedirs(out_dir, exist_ok=True)
    entries, srcs = {}, {}
    for cfg in configs:
        label = f"{cfg}@af{analysis_fps}" if analysis_fps else cfg
        srcs[label] = 0.0 if analysis_fps else source_rate(repo, cfg)
        got = measure_one(repo, label, cfg, cameras, out_dir, extra={"analysis_fps": analysis_fps} if analysis_fps else None,
                          src=srcs[label], tag=f"af{analysis_fps}" if analysis_fps else "", ceilings=not analysis_fps)
        entries.update(got)
        print(f"  {label}: source {srcs[label] or 'achieved'} fps; {sum(1 for e in got.values() if e.get('ran'))}/{len(got)} replays ran", flush=True)
    return summarize(entries, {k: v for k, v in srcs.items() if v})


def measure_models(repo: str, models: list, cameras: list, out_dir: str) -> dict:
    """The attendance detector swapped for each model: ceiling and cameras. The engine slots are backed up and put back."""
    os.makedirs(out_dir, exist_ok=True)
    backup = os.path.join(out_dir, "engine-backup")
    files = backup_engines(repo, backup)
    print(f"  engines protected: {len(files)} files", flush=True)
    temp_cfgs, entries, boot, srcs = [], {}, {}, {}
    try:
        cfg_of = {}
        for m in models:
            if m in MODELS:
                cfg_of[m] = MODELS[m][0]
            elif m.endswith("-fp16") and m[:-5] in MODELS:
                rel = os.path.join("perception", "models", "DeepStream-Yolo", f"config_infer_primary_{m.replace('-', '_')}.txt")
                with open(os.path.join(repo, rel), "w") as f:
                    f.write(fp16_config_text(_read(os.path.join(repo, MODELS[m[:-5]][0]))))
                temp_cfgs.append(os.path.join(repo, rel))
                cfg_of[m] = rel
            else:
                raise ValueError(f"unknown model {m!r}; known: {sorted(MODELS) + [k + '-fp16' for k in FP16_OF]}")
        src = source_rate(repo, "attendance")
        for m in models:
            got = measure_one(repo, m, "attendance", cameras, out_dir, extra={"pgie_config": "/workspace/iris/" + cfg_of[m]}, src=src)
            entries.update(got)
            srcs[m] = src
            boot[m] = (got.get((m, 1, False)) or {}).get("boot_s")
            print(f"  {m}: {sum(1 for e in got.values() if e.get('ran'))}/{len(got)} replays ran, first boot (engine build + start) {boot[m]} s", flush=True)
    finally:
        for p in temp_cfgs:
            try:
                os.remove(p)
            except OSError:
                pass
        restore_engines(repo, backup, files)
        print("  engines restored", flush=True)
    summary = summarize(entries, srcs)
    for m in summary:
        summary[m]["first_boot_s_with_engine_build"] = boot.get(m)
        summary[m]["precision"] = "fp16 (forced)" if m.endswith("-fp16") else MODELS.get(m, ("", "?"))[1]
    return summary


def measure_engines(repo: str, out_dir: str, image: str = "iris-deepstream-sidecar:latest") -> dict:
    """trtexec on each detector ONNX: GPU time per frame at batch 1, FP16 for all and FP32 for the sizes the product runs at FP32."""
    os.makedirs(out_dir, exist_ok=True)
    mdir = os.path.join(repo, "perception", "models", "DeepStream-Yolo")
    todo = [(m, "fp16") for m in ("yolo11s", "yolo11m", "yolo11l", "yolo11x", "damoyolo_s")] + [("yolo11l", "fp32"), ("yolo11x", "fp32")]
    out = {}
    for model, prec in todo:
        onnx = f"/m/{model}.onnx"
        cmd = ["docker", "run", "--rm", "--gpus", "all", "-v", f"{mdir}:/m:ro", "--entrypoint", "trtexec", image, f"--onnx={onnx}",
               "--warmUp=500", "--duration=8", "--iterations=200", "--noDataTransfers"] + (["--fp16"] if prec == "fp16" else [])
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=1800)
        text = r.stdout + r.stderr
        open(os.path.join(out_dir, f"trtexec-{model}-{prec}.log"), "w").write(text)
        parsed = parse_trtexec(text)
        out[f"{model}-{prec}"] = parsed or {"error": text.strip().splitlines()[-1][:160] if text.strip() else "no output"}
        print(f"  {model} {prec}: {out[f'{model}-{prec}']}", flush=True)
    return out


def results_doc(repo: str, limits: dict) -> dict:
    """The limits as a regress results file (schema regress.v1 with a `capacity` section): `regress compare` and `baseline` read it like any other."""
    from . import machine
    fp = machine.fingerprint(repo)
    cap = {cfg: {k: v for k, v in s.items() if k != "runs"} for cfg, s in limits.items()}
    noisy = any(s.get("noisy_steps") for s in limits.values())
    return {"schema": "regress.v1", "created": __import__("datetime").datetime.now(__import__("datetime").timezone.utc).isoformat(timespec="seconds"),
            "machine_id": fp["machine_id"], "fingerprint": fp, "noisy": noisy, "guardrails": {}, "correctness": {}, "runtime": {}, "build": {},
            "capacity": cap, "verdict": {"pass": True, "reasons": [], "known_failures": []}}


def main(repo: str, a) -> int:
    global RESUME
    RESUME = bool(getattr(a, "resume", False))
    out_dir = a.out or os.path.join(repo, "benchmarks", "runs", "capacity")
    cams = [int(x) for x in a.cameras.split(",") if x]
    result = {}
    if a.engines:
        print("engines (trtexec):", flush=True)
        result["engines"] = measure_engines(repo, out_dir)
    if a.models:
        names = list(MODELS) + [k + "-fp16" for k in FP16_OF] if a.models == "all" else [x for x in a.models.split(",") if x]
        print(f"models (attendance detector): {', '.join(names)}", flush=True)
        result["models"] = measure_models(repo, names, cams, out_dir)
        print(render(result["models"]), flush=True)
    if a.configs:
        cfgs = DEFAULT_CONFIGS if a.configs == "all" else [x for x in a.configs.split(",") if x]
        print(f"limits: {', '.join(cfgs)}; cameras {cams}", flush=True)
        result["limits"] = measure_limits(repo, cfgs, cams, out_dir, analysis_fps=int(getattr(a, "analysis_fps", 0) or 0))
        print(render(result["limits"]), flush=True)
        name = "capacity-results.json" if not getattr(a, "analysis_fps", 0) else f"capacity-results-af{a.analysis_fps}.json"
        json.dump(results_doc(repo, result["limits"]), open(os.path.join(out_dir, name), "w"), indent=1)
    path = os.path.join(out_dir, "capacity.json")
    json.dump(result, open(path, "w"), indent=1)
    print(f"written: {path}")
    return 0
