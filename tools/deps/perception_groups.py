#!/usr/bin/env python3
"""Generate the dependency groups of perception/pyproject.toml from the requirements files (the sidecar image's lock).

  perception_groups.py          rewrite the generated block of perception/pyproject.toml
  perception_groups.py --check  exit 1 when that block is not what the requirements files say

Each requirements.txt stays the place to declare a dependency (perception/engine/requirements.txt, and
perception/modules/<name>/requirements.txt for a module). They become one group each: `engine` and `module-<name>`.
The image targets become `slim` (engine + the Dockerfile's BASE_MODULES) and `mtmc` (slim + MTMC_MODULES + torch), so
`uv export --only-group slim` is exactly what the slim image installs. Run `uv lock` in perception/ afterwards
(`just deps-lock` does both).

Above each target the block records the module list it was generated from (`# slim: BASE_MODULES="..."`):
perception/pipeline/install_locked.sh compares it with the build's ARG and stops a build whose --build-arg differs,
which the lock's group could not honour.
"""
import argparse
import glob
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
PYPROJECT = os.path.join(ROOT, "perception", "pyproject.toml")
DOCKERFILE = os.path.join(ROOT, "perception", "pipeline", "Dockerfile")
ENGINE = os.path.join(ROOT, "perception", "engine", "requirements.txt")
MODULES = os.path.join(ROOT, "perception", "modules")
START = "# groups:start (generated by tools/deps/perception_groups.py from the requirements.txt files; do not edit)"
END = "# groups:end"
# The mtmc target installs these beyond its modules' requirements: CUDA torch, from the index in [tool.uv.sources].
MTMC_EXTRA = ["torch", "torchvision"]


def requirements(path):
    """The requirement lines of a requirements.txt, in file order, without comments."""
    out = []
    with open(path) as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if line:
                out.append(line)
    return out


def dockerfile_modules(arg):
    """The default of `ARG <arg>="a b c"` in the sidecar Dockerfile."""
    with open(DOCKERFILE) as f:
        m = re.search(rf'^ARG\s+{arg}="([^"]*)"', f.read(), re.M)
    if not m:
        sys.exit(f"{DOCKERFILE}: no ARG {arg}=\"...\"")
    return m.group(1).split()


def group_name(module):
    return "module-" + module.replace("_", "-")


def block():
    modules = sorted(os.path.basename(os.path.dirname(p)) for p in glob.glob(os.path.join(MODULES, "*", "requirements.txt")))
    base, mtmc = dockerfile_modules("BASE_MODULES"), dockerfile_modules("MTMC_MODULES")
    for m in base + mtmc:
        if m not in modules:
            sys.exit(f"{DOCKERFILE} names module {m!r}, which has no perception/modules/{m}/requirements.txt")
    q = lambda s: '"' + s.replace('"', '\\"') + '"'                          # noqa: E731
    inc = lambda g: f'{{ include-group = "{g}" }}'                          # noqa: E731
    lines = [START, "[dependency-groups]",
             "engine = [" + ", ".join(q(r) for r in requirements(ENGINE)) + "]"]
    for m in modules:
        reqs = requirements(os.path.join(MODULES, m, "requirements.txt"))
        lines.append(f"{group_name(m)} = [" + ", ".join(q(r) for r in reqs) + "]")
    lines.append(f'# slim: BASE_MODULES="{" ".join(base)}"')
    lines.append("slim = [" + ", ".join([inc("engine")] + [inc(group_name(m)) for m in base]) + "]")
    lines.append(f'# mtmc: MTMC_MODULES="{" ".join(mtmc)}"')
    lines.append("mtmc = [" + ", ".join([inc("slim")] + [inc(group_name(m)) for m in mtmc] + [q(r) for r in MTMC_EXTRA])
                 + "]")
    lines.append(END)
    return "\n".join(lines) + "\n"


def current():
    with open(PYPROJECT) as f:
        text = f.read()
    i, j = text.find(START), text.find(END)
    if i < 0 or j < 0:
        sys.exit(f"{PYPROJECT}: the markers {START!r} / {END!r} are missing")
    return text, i, j + len(END) + 1


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text, i, j = current()
    new = text[:i] + block() + text[j:]
    if args.check:
        if new != text:
            print("perception/pyproject.toml is out of date with the requirements.txt files: run `just deps-lock`",
                  file=sys.stderr)
            return 1
        return 0
    if new != text:
        with open(PYPROJECT, "w") as f:
            f.write(new)
        print("perception/pyproject.toml: groups regenerated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
