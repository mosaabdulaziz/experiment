def label(lang: str, key: str) -> str:
    return TEXT[lang][key]


def kind_title(lang: str, kind: str) -> str:
    return TEXT[lang][f"kind.{kind}"]


def timer(seconds: float | None) -> str:
    if seconds is None:
        return "—"
    s = max(0, int(seconds))
    if s >= 3600:
        return f"{s // 3600}:{s % 3600 // 60:02d}:{s % 60:02d}"
    return f"{s // 60:02d}:{s % 60:02d}"


def clock(iso: str | None) -> str:
    return iso[11:16] if iso else "—"


def number(n: float | None, digits: int = 0) -> str:
    return "—" if n is None else f"{n:,.{digits}f}"


def percent(share: dict | None) -> str:
    if not share:
        return "—"
    return f"{share['count']}" if share.get("percent") is None else f"{share['count']} ({share['percent']:g} %)"


def day_name(lang: str, iso_day: str) -> str:
    d = date.fromisoformat(iso_day[:10])
    return f"{WEEKDAYS[lang][d.weekday()]} {d.day} {MONTHS[lang][d.month - 1]}"


def stamp(lang: str, iso: str) -> str:
    """A date and time: "Sun 11 Oct 20:05"."""
    return f"{day_name(lang, iso)} {clock(iso)}"
