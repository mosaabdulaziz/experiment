import io
import struct
import zlib

from docx import Document

from report_docx import render_docx
from test_report_html import M

def _png() -> bytes:
    """A valid 1x1 white PNG (python-docx reads the image's chunks)."""
    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 1, 1, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(b"\x00\xff\xff\xff")) + chunk(b"IEND", b""))


PNG = _png()


def doc(model, lang, lan=True):
    return Document(io.BytesIO(render_docx(model, lang, lambda a: None, lan, lambda svg, w, h: PNG)))


def test_word_has_the_same_sections_in_order():
    d = doc(M, "en")
    heads = [p.text for p in d.paragraphs if p.style.name.startswith("Heading")]
    keys = ["Summary", "Charts", "Barbers", "Chairs", "Alerts", "Appendix"]
    assert [h for h in heads if h in keys] == keys
    assert any("Palm Hills" in p.text for p in d.paragraphs)
    assert len(d.tables) >= 4


def test_arabic_word_is_right_to_left():
    d = doc(M, "ar")
    xml = d.element.xml
    assert "<w:bidi/>" in xml and "<w:rtl/>" in xml and "<w:bidiVisual/>" in xml


def test_bidi_visual_sits_where_word_expects_it():
    d = doc(M, "ar")
    for t in d.tables:
        tags = [c.tag.split("}")[1] for c in t._tbl.tblPr]
        assert tags.index("bidiVisual") == tags.index("tblStyle") + 1


def test_word_has_an_a4_page_with_the_iris_header_and_numbered_footer():
    d = doc(M, "en")
    s = d.sections[0]
    assert abs(s.page_width.mm - 210) < 1 and abs(s.page_height.mm - 297) < 1
    head = s.header._element.xml
    assert "<w:drawing" in head and "BEKKY BARBER" in head          # IRIS mark + the shop wordmark
    foot = s.footer._element.xml
    assert 'w:instr="PAGE"' in foot and 'w:instr="NUMPAGES"' in foot and "Generated by IRIS" in foot


def test_word_tables_have_a_shaded_header_row_and_figure_cards():
    d = doc(M, "en")
    xml = d.element.xml
    assert 'w:fill="1B7A52"' in xml                               # the header rows
    cards = d.tables[0]
    assert len(cards.columns) == 4 and "Served customers" in cards._tbl.xml


def test_a_shop_logo_goes_into_the_word_header():
    import io as _io
    from docx import Document as _D
    d = _D(_io.BytesIO(render_docx(M, "en", lambda a: None, True, lambda svg, w, h: PNG, shop_logo=(PNG, "image/png"))))
    head = d.sections[0].header._element.xml
    assert head.count("<w:drawing") == 2 and "BEKKY BARBER" not in head


