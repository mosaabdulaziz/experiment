"""The report as a Word document: the HTML report's sections, order and tables (spec section 3), charts as PNG
(rendered from the same SVG by headless Chrome, at 2x), snapshots as pictures, Arabic set right-to-left (paragraph
bidi, rtl runs, table bidiVisual). 2026-10-15 (user: a more professional layout): A4, a page header with the IRIS mark
and the shop's logo (or its wordmark), a footer "Generated by IRIS" + Page X of Y, figure cards, tables with a shaded
header row and banded rows, the appendix on a new page."""
from __future__ import annotations

import io
from typing import Callable

from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_BREAK
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Inches, Mm, Pt, RGBColor

from report_html import (IRIS_SVG, _end, alert_rows, bars_svg, barber_items, figure_cards, haircut_rows, low_list,
                         low_marks, period_text, served_note,
                         series_items, wordmark)
from report_text import clock, day_name, kind_title, label, number, stamp, timer

FONT = "Arial"
GREEN, AMBER, BLUE, INK, MUTE, LINE, GROUND, BAND = "1B7A52", "B7791F", "3B7FD6", "17251F", "5C6B63", "D8DEDB", "EEF1EF", "F6F8F7"
LOW = "FFF1B8"                      # a low-occupancy haircut's row (report_html.LOW)
TONE = {"count": GREEN, "time": BLUE, "alert": AMBER}


def _rgb(hexs: str) -> RGBColor:
    return RGBColor.from_string(hexs)


def _rtl_par(p) -> None:
    ppr = p._p.get_or_add_pPr()
    if ppr.find(qn("w:bidi")) is None:
        ppr.append(OxmlElement("w:bidi"))
    for r in p.runs:
        rpr = r._r.get_or_add_rPr()
        if rpr.find(qn("w:rtl")) is None:
            rpr.append(OxmlElement("w:rtl"))


def _font(run) -> None:
    run.font.name = FONT
    rpr = run._r.get_or_add_rPr()
    fonts = rpr.find(qn("w:rFonts"))
    if fonts is None:
        fonts = OxmlElement("w:rFonts")
        rpr.append(fonts)
    fonts.set(qn("w:cs"), FONT)


def _shade(cell, fill: str) -> None:
    tcpr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), fill)
    tcpr.append(shd)


def _borders(table, color: str, inner: bool = True) -> None:
    tpr = table._tbl.tblPr
    b = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right") + (("insideH", "insideV") if inner else ()):
        e = OxmlElement(f"w:{edge}")
        e.set(qn("w:val"), "single")
        e.set(qn("w:sz"), "4")
        e.set(qn("w:color"), color)
        b.append(e)
    tpr.append(b)


def _rule_below(p, color: str) -> None:
    ppr = p._p.get_or_add_pPr()
    bdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    for k, v in (("val", "single"), ("sz", "12"), ("space", "2"), ("color", color)):
        bottom.set(qn(f"w:{k}"), v)
    bdr.append(bottom)
    ppr.append(bdr)


def _field(p, instr: str) -> None:
    f = OxmlElement("w:fldSimple")
    f.set(qn("w:instr"), instr)
    r = OxmlElement("w:r")
    t = OxmlElement("w:t")
    t.text = "1"
    r.append(t)
    f.append(r)
    p._p.append(f)


class _Doc:
    def __init__(self, lang: str):
        self.d, self.rtl = Document(), lang == "ar"
        st = self.d.styles["Normal"]
        st.font.size, st.font.name = Pt(10), FONT
        st.font.color.rgb = _rgb(INK)
        for name, size in (("Heading 1", 13), ("Heading 2", 11), ("Heading 3", 10)):
            h = self.d.styles[name]
            h.font.name, h.font.size, h.font.bold = FONT, Pt(size), True
            h.font.color.rgb = _rgb(GREEN if name == "Heading 1" else INK)
        s = self.d.sections[0]
        s.page_width, s.page_height = Mm(210), Mm(297)
        s.left_margin = s.right_margin = Mm(15)
        s.top_margin, s.bottom_margin = Mm(14), Mm(16)
        self.width = s.page_width - s.left_margin - s.right_margin

    def fix(self, p, align_end: bool = False):
        for r in p.runs:
            _font(r)
        if self.rtl:
            _rtl_par(p)
        if align_end:
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT if self.rtl else WD_ALIGN_PARAGRAPH.RIGHT
        return p

    def heading(self, text: str, level: int):
        p = self.fix(self.d.add_heading(text, level))
        if level == 1:
            _rule_below(p, GREEN)
        return p

    def para(self, text: str, size: float | None = None, color: str | None = None, bold: bool = False):
        p = self.d.add_paragraph()
        r = p.add_run(text)
        if size:
            r.font.size = Pt(size)
        if color:
            r.font.color.rgb = _rgb(color)
        r.bold = bold
        return self.fix(p)

    def _bidi_table(self, t) -> None:
        if self.rtl:                                 # right after tblStyle, as the schema orders it (final review I3)
            tpr = t._tbl.tblPr
            style = tpr.find(qn("w:tblStyle"))
            tpr.insert(list(tpr).index(style) + 1 if style is not None else 0, OxmlElement("w:bidiVisual"))

    def table(self, head: list[str], rows: list[list[str]], num: tuple[int, ...] = (), mark: frozenset = frozenset()):
        t = self.d.add_table(rows=1, cols=len(head))
        t.style = "Table Grid"
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        self._bidi_table(t)
        _borders(t, LINE)
        for i, (cell, h) in enumerate(zip(t.rows[0].cells, head)):
            cell.text = str(h)
            _shade(cell, GREEN)
            for r in cell.paragraphs[0].runs:
                r.bold, r.font.color.rgb, r.font.size = True, _rgb("FFFFFF"), Pt(9.5)
        for k, row in enumerate(rows):
            cells = t.add_row().cells
            for i, (cell, v) in enumerate(zip(cells, row)):
                cell.text = str(v)
                if k in mark:                       # a low-occupancy haircut (2026-11-14)
                    _shade(cell, LOW)
                elif k % 2:
                    _shade(cell, BAND)
                for r in cell.paragraphs[0].runs:
                    r.font.size = Pt(9.5)
        for row in t.rows:
            for i, cell in enumerate(row.cells):
                for p in cell.paragraphs:
                    self.fix(p, align_end=i in num)
        self.d.add_paragraph()
        return t

    def cards(self, items: list[tuple[str, str, str]], note: str = ""):
        """note: a small line under the first card's value (Served customers: its low-occupancy haircuts)."""
        cols = 4
        t = self.d.add_table(rows=(len(items) + cols - 1) // cols, cols=cols)
        t.style = "Table Grid"
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        self._bidi_table(t)
        _borders(t, "FFFFFF")
        for i, (k, v, tone) in enumerate(items):
            cell = t.rows[i // cols].cells[i % cols]
            _shade(cell, GROUND)
            p = cell.paragraphs[0]
            r = p.add_run(k)
            r.font.size, r.font.color.rgb = Pt(8.5), _rgb(MUTE)
            p2 = cell.add_paragraph()
            r2 = p2.add_run(v)
            r2.font.size, r2.bold, r2.font.color.rgb = Pt(15), True, _rgb(TONE.get(tone, GREEN))
            ps = [p, p2]
            if note and i == 0:
                ps.append(cell.add_paragraph())
                r3 = ps[-1].add_run(note)
                r3.font.size, r3.font.color.rgb = Pt(8.5), _rgb(INK)
            for q in ps:
                self.fix(q)
        self.d.add_paragraph()
        return t

    def picture(self, data: bytes, width_in: float):
        self.d.add_picture(io.BytesIO(data), width=Inches(width_in))
        self.fix(self.d.paragraphs[-1])

    def page_break(self):
        self.d.add_paragraph().add_run().add_break(WD_BREAK.PAGE)


def _header(w: _Doc, model: dict, lang: str, png, shop_logo) -> None:
    s, sec = model["site"], w.d.sections[0]
    t = sec.header.add_table(rows=1, cols=3, width=w.width)
    t.style = "Table Grid"
    w._bidi_table(t)
    _borders(t, "FFFFFF")
    a, b, c = t.rows[0].cells
    a.paragraphs[0].add_run().add_picture(io.BytesIO(png(IRIS_SVG.replace('width="44" height="44"', 'width="96" height="96"'), 96, 96)),
                                          width=Mm(13))
    r = b.paragraphs[0].add_run(label(lang, "title"))
    r.bold, r.font.size, r.font.color.rgb = True, Pt(14), _rgb(GREEN)
    sub = b.add_paragraph().add_run(f'{s["place"]} — {s["branch"]} · {kind_title(lang, model["kind"])}')
    sub.font.size = Pt(9.5)
    per = b.add_paragraph().add_run(period_text(model, lang))
    per.font.size, per.font.color.rgb = Pt(9), _rgb(MUTE)
    pc = c.paragraphs[0]
    if shop_logo:
        data, mime = shop_logo
        if mime == "image/svg+xml":
            data = png(data.decode(), 320, 120)
        pc.add_run().add_picture(io.BytesIO(data), height=Mm(13))
    else:
        mark = pc.add_run(wordmark(s["place"]))
        mark.bold, mark.font.size, mark.font.color.rgb = True, Pt(12), _rgb(GREEN)
    for cell in (a, b, c):
        for p in cell.paragraphs:
            w.fix(p)
    pc.alignment = WD_ALIGN_PARAGRAPH.LEFT if w.rtl else WD_ALIGN_PARAGRAPH.RIGHT
    rule = sec.header.add_paragraph()
    _rule_below(rule, GREEN)


def _footer(w: _Doc, model: dict, lang: str) -> None:
    p = w.d.sections[0].footer.paragraphs[0]
    r = p.add_run(f'{label(lang, "generatedBy")} · {stamp(lang, model["generated_at"])}    |    {label(lang, "page")} ')
    _field(p, "PAGE")
    p.add_run(f' {label(lang, "of")} ')
    _field(p, "NUMPAGES")
    for run in p.runs:
        run.font.size, run.font.color.rgb = Pt(8.5), _rgb(MUTE)
    w.fix(p)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    del r


def render_docx(model: dict, lang: str, image: Callable[[str], bytes | None], lan: bool,
                png: Callable[[str, int, int], bytes], shop_logo: tuple[bytes, str] | None = None) -> bytes:
    w, day = _Doc(lang), model["kind"] == "day"
    L = lambda k: label(lang, k)
    _header(w, model, lang, png, shop_logo)
    _footer(w, model, lang)
    s = model["site"]
    w.para(f'{L("generated")}: {stamp(lang, model["generated_at"])} · {L("dayStarts")} {model["day_start_hour"]:02d}:00 · '
           f'{s["place"]} — {s["branch"]}', size=8.5, color=MUTE)
    w.heading(L("summary"), 1)
    w.cards(figure_cards(model, lang), served_note(model, lang))
    w.heading(L("charts"), 1)
    for title, items in ((L("ch.haircuts"), series_items(model, lang)), (L("ch.perBarber"), barber_items(model, lang))):
        w.heading(title, 2)
        w.picture(png(bars_svg(items, 900, 230, w.rtl, L("ch.noData")), 900, 230), 6.9)
    w.heading(L("barbers"), 1)
    if model["barbers"]:
        w.table([L("col.barber"), L("col.haircuts"), L("col.avg")],
                [[b["name"] or L("noBarber"), number(b["haircuts"]), timer(b["average_haircut_s"])] for b in model["barbers"]],
                num=(1, 2))
    else:
        w.para(L("ch.noData"), color=MUTE)
    w.heading(L("chairs"), 1)
    hc_head = [L(k) for k in ("col.start", "col.end", "col.duration", "col.barber", "col.excessive")]
    if not model["chairs"]:
        w.para(L("ch.noData"), color=MUTE)
    else:
        w.table([L("col.chair"), L("col.haircuts"), L("col.total"), L("col.avg")],
                [[c["chair"], number(c["haircuts"]), timer(c["total_s"]), timer(c["average_s"])] for c in model["chairs"]],
                num=(1, 2, 3))
    if low_list(model):
        w.para(L("lowOcc.note"), size=8.5, color=MUTE)
    for c in model["chairs"]:
        if day:
            w.heading(c["chair"], 2)
            w.table(hc_head, haircut_rows(c["rows"], lang), num=(2,), mark=low_marks(c["rows"]))
        else:
            w.heading(f'{c["chair"]} — {L("perDay")}', 2)
            w.table([L("col.day"), L("col.haircuts"), L("col.total")],
                    [[day_name(lang, d["day"]), number(d["haircuts"]), timer(d["total_s"])] for d in c["days"]], num=(1, 2))
    ped = model.get("pedicure") or {"count": 0, "chairs": []}
    if ped["count"]:                                # 2026-11-10: pedicure chairs, never customers
        when = clock if day else (lambda v: stamp(lang, v))
        w.heading(L("pedicure"), 1)
        w.para(L("pedicure.line").format(n=number(ped["count"]), t=timer(ped["total_s"])))
        for c in ped["chairs"]:
            w.heading(c["chair"], 2)
            w.table([L("col.start"), L("col.end"), L("col.duration")],
                    [[when(r["start"]), _end(r, lang), timer(r["duration_s"])] for r in c["rows"]], num=(2,))
    al = model["alerts"]
    w.heading(L("alerts"), 1)
    w.table([L("col.kind"), L("col.count")], [[L("alert.excessive_wait"), number(al["counts"]["excessive_wait"])],
                                              [L("alert.excessive_service"), number(al["counts"]["excessive_service"])]],
            num=(1,))
    by_id = {a["id"]: a for a in al["rows"]}
    if al["shown"]:
        w.heading(L("snapshots") if day else L("longest"), 2)
        t = w.d.add_table(rows=(len(al["shown"]) + 1) // 2, cols=2)
        t.style = "Table Grid"
        w._bidi_table(t)
        _borders(t, LINE)
        for i, aid in enumerate(al["shown"]):
            a = by_id[aid]
            cell = t.rows[i // 2].cells[i % 2]
            jpg = image(aid) if lan else None
            p = cell.paragraphs[0]
            if jpg:
                p.add_run().add_picture(io.BytesIO(jpg), width=Inches(3.2))
            else:
                p.add_run(f'[{L("lanOnly") if not lan else L("noSnapshot")}]').font.color.rgb = _rgb(MUTE)
            cap = cell.add_paragraph().add_run(f'{L("alert." + a["kind"])} · {a["chair"] or "—"} · '
                                              f'{stamp(lang, a["start"])} · {timer(a["duration_s"])}')
            cap.font.size, cap.font.color.rgb = Pt(8.5), _rgb(MUTE)
            for q in cell.paragraphs:
                w.fix(q)
        w.d.add_paragraph()
    alert_head = [L(k) for k in ("col.kind", "col.chair", "col.barber", "col.start", "col.end", "col.duration")]
    if day and al["rows"]:
        w.table(alert_head, alert_rows(al["rows"], lang), num=(5,))
    if not day:
        w.page_break()
        w.heading(L("appendix"), 1)
        for c in model["chairs"]:
            w.heading(f'{c["chair"]} — {L("haircutList")}', 2)
            for d in c["days"]:
                w.heading(day_name(lang, d["day"]), 3)
                rs = [r for r in c["rows"] if r["day"] == d["day"]]
                w.table(hc_head, haircut_rows(rs, lang), num=(2,), mark=low_marks(rs))
        if al["rows"]:
            w.heading(L("alertList"), 2)
            w.table(alert_head, alert_rows(al["rows"], lang), num=(5,))
        if not model["chairs"] and not al["rows"]:
            w.para(L("ch.noData"), color=MUTE)
    buf = io.BytesIO()
    w.d.save(buf)
    return buf.getvalue()
